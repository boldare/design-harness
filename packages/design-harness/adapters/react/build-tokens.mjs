// Builds the system's CSS custom properties (paths.tokens_css) from its tokens file (paths.tokens, the source of truth).
// Naming follows the Figma library's naming rules: token name with '.' replaced by '-' (surface.page -> --surface-page).

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { loadSystem } from '../../lib/manifest.mjs';

const system = loadSystem();
const source = system.at(system.paths.tokens);
const target = system.at(system.paths.tokens_css);

const tokens = JSON.parse(readFileSync(source, 'utf8'));

const cssName = (tokenName) => `--${tokenName.replaceAll('.', '-')}`;
// Aliases such as "{neutral.50}" become var(--neutral-50), also inside longer values like shadows.
const resolve = (value) => String(value).replace(/\{([^}]+)\}/g, (_, ref) => `var(${cssName(ref)})`);
const kebab = (key) => key.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);
const declaration = (name, value) => `  ${name}: ${resolve(value)};`;
const block = (selector, lines) => `${selector} {\n${lines.join('\n')}\n}`;

// Colour: primitives once, semantic tokens per theme. The first theme is the default (:root).
const [defaultTheme, ...otherThemes] = tokens.color.themes.map((theme) => theme.id);
const primitives = tokens.color.tokens.filter((token) => typeof token.value === 'string');
const semantic = tokens.color.tokens.filter((token) => typeof token.value === 'object');
const semanticFor = (theme) => semantic.map((token) => declaration(cssName(token.name), token.value[theme]));

// Every other family is a flat list of { name, value }.
// Families are read from the file, so a new one (for example layer) needs no change here.
const families = Object.keys(tokens).filter((key) => !['color', 'type'].includes(key) && Array.isArray(tokens[key]?.tokens));

// A token that points at a semantic colour (a shadow in border.control) is declared again in every theme block:
// var() resolves where the property is declared, so one declaration on :root would keep the default theme's colour
// in a section with its own data-theme. Found to a fixed point, so a token pointing at such a token follows too.
const themed = new Set(semantic.map((token) => token.name));
const others = families.flatMap((family) => tokens[family].tokens);
const references = (value) => [...String(value).matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
let grew = true;
while (grew) {
  grew = false;
  for (const token of others) {
    if (!themed.has(token.name) && references(token.value).some((ref) => themed.has(ref))) {
      themed.add(token.name);
      grew = true;
    }
  }
}
const dependents = others.filter((token) => themed.has(token.name)).map((token) => declaration(cssName(token.name), token.value));

// Type: one variable per property of each style, plus a utility class that applies them.
const typeProperties = (style) => Object.keys(style).filter((key) => key !== 'name' && key !== 'usage');
const typeVariable = (style, key) => `--type-${style.name}-${kebab(key)}`;
const typeStyles = tokens.type.groups.flatMap((group) => group.styles.map((style) => ({ style, family: group.family })));

const rootLines = [
  '  /* Colour primitives */',
  ...primitives.map((token) => declaration(cssName(token.name), token.value)),
  '',
  `  /* Semantic colour, ${defaultTheme} */`,
  ...semanticFor(defaultTheme),
  ...families.flatMap((family) => [
    '',
    `  /* ${family} */`,
    ...tokens[family].tokens.map((token) => declaration(cssName(token.name), token.value)),
  ]),
  '',
  '  /* Type */',
  ...Object.entries(tokens.type.families).map(([name, value]) => declaration(`--font-${name}`, value)),
  ...typeStyles.flatMap(({ style }) => typeProperties(style).map((key) => declaration(typeVariable(style, key), style[key]))),
];

// The default theme also gets a block, so a section can return to it inside another theme.
const themeBlocks = [defaultTheme, ...otherThemes].map((theme) => block(`[data-theme="${theme}"]`, [...semanticFor(theme), ...dependents]));

const typeClasses = typeStyles.map(({ style, family }) =>
  block(`.type-${style.name}`, [
    `  font-family: var(--font-${family});`,
    ...typeProperties(style).map((key) => `  ${kebab(key)}: var(${typeVariable(style, key)});`),
  ]),
);

const css = [
  `/* Generated by design-harness tokens from ${system.rel(source)}. Do not edit: change the tokens and run \`npm run tokens\`. */`,
  otherThemes.length
    ? `/* Themes: ${defaultTheme} is the default; set data-theme on the root element or on a section for ${otherThemes.join(', ')}. */`
    : `/* Theme: ${defaultTheme}, the only one. */`,
  '',
  block(':root', rootLines),
  '',
  ...themeBlocks.flatMap((themeBlock) => [themeBlock, '']),
  '/* Type styles */',
  typeClasses.join('\n\n'),
  '',
].join('\n');

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, css);
console.log(`Wrote ${system.rel(target)}`);
