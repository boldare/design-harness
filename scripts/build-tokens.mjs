// Builds src/styles/tokens.css from tokens/tokens.json (the source of truth).
// Naming follows figma/library.json: token name with '.' replaced by '-' (surface.page -> --surface-page).

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = join(root, 'tokens/tokens.json');
const target = join(root, 'src/styles/tokens.css');

const tokens = JSON.parse(readFileSync(source, 'utf8'));

const cssName = (tokenName) => `--${tokenName.replaceAll('.', '-')}`;
// Aliases such as "{neutral.50}" become var(--neutral-50), also inside longer values like shadows.
const resolve = (value) => String(value).replace(/\{([^}]+)\}/g, (_, ref) => `var(${cssName(ref)})`);
const kebab = (key) => key.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);
const declaration = (name, value) => `  ${name}: ${resolve(value)};`;
const block = (selector, lines) => `${selector} {\n${lines.join('\n')}\n}`;

// Colour: primitives once, semantic tokens per theme. The first theme is the default (:root).
const [defaultTheme, ...otherThemes] = tokens.color.themes.map((theme) => theme.id);
const primitives = tokens.color.tokens.filter((token) => typeof token.value === 'string');
const semantic = tokens.color.tokens.filter((token) => typeof token.value === 'object');
const semanticFor = (theme) => semantic.map((token) => declaration(cssName(token.name), token.value[theme]));

// Every other family is a flat list of { name, value }.
const families = ['spacing', 'radius', 'size', 'stroke', 'shadow', 'opacity', 'duration'];

// Type: one variable per property of each style, plus a utility class that applies them.
const typeProperties = (style) => Object.keys(style).filter((key) => key !== 'name' && key !== 'usage');
const typeVariable = (style, key) => `--type-${style.name}-${kebab(key)}`;
const typeStyles = tokens.type.groups.flatMap((group) => group.styles.map((style) => ({ style, family: group.family })));

const rootLines = [
  '  /* Colour primitives */',
  ...primitives.map((token) => declaration(cssName(token.name), token.value)),
  '',
  `  /* Semantic colour, ${defaultTheme} */`,
  ...semanticFor(defaultTheme),
  ...families.flatMap((family) => [
    '',
    `  /* ${family} */`,
    ...tokens[family].tokens.map((token) => declaration(cssName(token.name), token.value)),
  ]),
  '',
  '  /* Type */',
  ...Object.entries(tokens.type.families).map(([name, value]) => declaration(`--font-${name}`, value)),
  ...typeStyles.flatMap(({ style }) => typeProperties(style).map((key) => declaration(typeVariable(style, key), style[key]))),
];

const themeBlocks = otherThemes.map((theme) => block(`[data-theme="${theme}"]`, semanticFor(theme)));

const typeClasses = typeStyles.map(({ style, family }) =>
  block(`.type-${style.name}`, [
    `  font-family: var(--font-${family});`,
    ...typeProperties(style).map((key) => `  ${kebab(key)}: var(${typeVariable(style, key)});`),
  ]),
);

const css = [
  '/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit: change the tokens and run `npm run tokens`. */',
  `/* Themes: ${defaultTheme} is the default; set data-theme on the root element for ${otherThemes.join(', ')}. */`,
  '',
  block(':root', rootLines),
  '',
  ...themeBlocks.flatMap((themeBlock) => [themeBlock, '']),
  '/* Type styles */',
  typeClasses.join('\n\n'),
  '',
].join('\n');

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, css);
console.log(`Wrote ${target.replace(root, '')}`);
